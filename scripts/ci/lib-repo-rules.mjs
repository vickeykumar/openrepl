// The rules a pull request has to keep (scripts/ci/repo-rules.mjs runs them on the
// files it changes). Pure functions, so they are unit tested (src/js/test/repo-rules.test.mjs).
//
// 1. Build output and secrets are never committed. bin/gotty, src/js/dist, the
//    generated src/server/asset.go and src/bindata are made by the build; an env
//    file or a key file holds secrets.
// 2. A file that uses CRLF line endings keeps them (Makefile, server.go, xterm.ts...):
//    an editor that rewrites every line makes the diff unreadable.
// 3. A change to the server, the build or the page script comes with a change to the
//    docs (docs/lld). This one only warns.

const FORBIDDEN = [
  { test: (f) => f === "bin/gotty", why: "the built server binary (restore it with `git checkout -- bin/gotty`)" },
  { test: (f) => f === "src/server/asset.go", why: "generated by `make asset`" },
  { test: (f) => f.startsWith("src/js/dist/"), why: "webpack output" },
  { test: (f) => f.startsWith("src/resources/chat-widget/dist/"), why: "the widget bundle, made by its build" },
  { test: (f) => f.startsWith("src/bindata/") || f.startsWith("bindata/"), why: "the embedded assets, made by `make asset`" },
  { test: (f) => /(^|\/)node_modules\//.test(f), why: "installed packages" },
  { test: (f) => /(^|\/)\.env(\.|$)/.test(f) && !/(^|\/)\.env\.example$/.test(f), why: "an env file holds secrets (only .env.example belongs in git)" },
  { test: (f) => /\.(pem|p12|pfx)$/i.test(f), why: "a key or certificate" },
  { test: (f) => /(service-?account|credentials?)[^/]*\.json$/i.test(f), why: "a service account or credentials file" },
  { test: (f) => /(^|\/)\.DS_Store$/.test(f), why: "a macOS folder file" },
];

// files that were deleted are not a problem: the caller passes the files a change adds or modifies
export function forbiddenPaths(files) {
  const out = [];
  for (const f of files) {
    const hit = FORBIDDEN.find((r) => r.test(f));
    if (hit) out.push({ file: f, why: hit.why });
  }
  return out;
}

function crlfShare(text) {
  if (!text) return 0;
  const lines = text.split("\n");
  if (lines.length && lines[lines.length - 1] === "") lines.pop();
  if (lines.length === 0) return 0;
  let crlf = 0;
  for (const l of lines) if (l.endsWith("\r")) crlf++;
  return crlf / lines.length;
}

// A file that was mostly CRLF in the base must still be mostly CRLF. `read(file)`
// gives {base, head} (strings; base is null for a new file).
export function lineEndingProblems(files, read) {
  const out = [];
  for (const f of files) {
    const { base, head } = read(f);
    if (base == null || head == null) continue;
    if (base.includes("\u0000") || head.includes("\u0000")) continue; // not text
    if (crlfShare(base) >= 0.5 && crlfShare(head) < 0.5) {
      out.push({ file: f, why: "this file uses CRLF line endings and the change turned them into LF" });
    }
  }
  return out;
}

const CODE_AREAS = [
  /^src\/server\/.*\.go$/,
  /^src\/gateway\/.*\.go$/,
  /^src\/utils\/config\.go$/,
  /^src\/Makefile$/,
  /^Dockerfile$/,
  /^src\/js\/src\//,
  /^src\/resources\/(js|css)\//,
  /^src\/resources\/chat-widget\/src\//,
];
const TEST_FILE = /(_test\.go|\.test\.(m?js|ts))$/;

// A reminder (not an error) when code changes and no document does.
export function docsReminder(files) {
  const code = files.filter((f) => CODE_AREAS.some((re) => re.test(f)) && !TEST_FILE.test(f));
  const docs = files.filter((f) => f.startsWith("docs/") || f === "README.md" || f.startsWith("src/resources/knowledge/"));
  if (code.length > 0 && docs.length === 0) {
    return `${code.length} code file(s) changed (for example ${code[0]}) and no document did. If a route, a store, a setting, the build or something a visitor sees changed, update the matching docs/lld page (and the Genie notes in src/resources/knowledge).`;
  }
  return null;
}
